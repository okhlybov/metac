class Source(_EntityContainer, _SmartRenderer):
  
  complexity = 0
  __stream = None

  def __init__(self, module, index, *args, **kwargs):
    super().__init__(*args, **kwargs)
    self.module = module
    self.index = index
    self.file_name = self._generate_file_name(self.module.name, self.index, self.module.source_count)

  @classmethod
  def _generate_file_name(self, prefix, index, count):
    return f"{prefix}_auto{index}.c" if count > 1 else f"{prefix}_auto.c"

  @property
  def stream(self):
    if self.__stream is None:
      self.__stream = _StreamFile(os.path.join(self.module.directory, self.file_name + "~"))
    return self.__stream

  def add(self, entity):
    if entity not in self.entities:
      self.complexity += entity.complexity
    self.entities.add(entity)
    return self

  def render_contents(self, stream):
    self.render_prologue(stream)
    total_entities = set()
    for e in self.entities:
      total_entities.update(e.total_references)
    for e in _sort_entities(total_entities):
      for chunk in e._source_declarations:
        stream.write(chunk)
    for e in _sort_entities(self.entities):
      for chunk in e._source_definitions:
        stream.write(chunk)

  def render_prologue(self, stream):
    stream.write(f"""
      {_caption}
      #include "{self.module.header.file_name}"
    """.lstrip())


