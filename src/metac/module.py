class Header(_EntityContainer, _SmartRenderer):
  
  __stream = None
  
  def __init__(self, module, *args, **kwargs):
    super().__init__(*args, **kwargs)
    self.module = module
    self.file_name = f"{self.module.name}_auto.h"

  @property
  def tag(self):
    clean = re.sub(r'[^A-Za-z0-9_]', '_', self.module.name)
    return f"{clean}_auto_h".upper()

  @property
  def stream(self):
    if self.__stream is None:
      self.__stream = _StreamFile(os.path.join(self.module.directory, self.file_name + "~"))
    return self.__stream

  def render_prologue(self, stream):
    stream.write(f"""
      {_caption}
      #ifndef {self.tag}
      #define {self.tag}
    """.lstrip())

  def render_contents(self, stream):
    self.render_prologue(stream)
    entities = _sort_entities(self.entities)
    for e in entities:
      for chunk in e._header_declarations:
        stream.write(chunk)
    for e in entities:
      for chunk in e._header_definitions:
        stream.write(chunk)
    self.render_epilogue(stream)

  def render_epilogue(self, stream):
    stream.write("\n#endif\n")


