class Entity:
  
  __hdefs = None
  __sdefs = None
  __hdecls = None
  __sdecls = None
  __position = None
  __total_references = None
  __total_dependencies = None
  __order_key = None
  
  def __init__(self, *args, dependencies=(), references=(), **kwargs):
    super().__init__(*args, **kwargs)
    self.references = set()
    self.references.update(references)
    self.dependencies = _DependencySet(self)
    self.dependencies.update(dependencies)

  @property
  def _order_key(self):
    # Total order over entities: topological position first, then the rendered
    # contents - this keeps the generation deterministic across the processes
    # by eliminating the set iteration order from the output
    if self.__order_key is None:
      self.__order_key = (
        self.position,
        str().join(self._header_declarations),
        str().join(self._source_declarations),
        str().join(self._source_definitions)
      )
    return self.__order_key

  def __lt__(self, other):
    return self._order_key < other._order_key

  @property
  def total_references(self):
    if self.__total_references is None:
      self.__total_references = self.collect_references(set())
    return self.__total_references

  @property
  def total_dependencies(self):
    if self.__total_dependencies is None:
      self.__total_dependencies = self.collect_dependencies(set())
    return self.__total_dependencies

  def collect_references(self, entities):
    if self not in entities:
      entities.add(self)
      if self.__total_references is not None:
        entities.update(self.__total_references)
      else:
        for ref in self.references:
          ref.collect_references(entities)
    return entities

  def collect_dependencies(self, entities):
    if self not in entities:
      entities.add(self)
      if self.__total_dependencies is not None:
        entities.update(self.__total_dependencies)
      else:
        for dep in self.dependencies:
          dep.collect_dependencies(entities)
    return entities

  @property
  def position(self):
    if self.__position is None:
      p = 0
      for d in self.total_dependencies:
        if d is not self:
          p = max(p, d.position)
      self.__position = p + 1
    return self.__position

  @property
  def complexity(self):
    return self._source_declarations.complexity + self._source_definitions.complexity

  def render_declarations(self, stream, header): pass
  
  def render_definitions(self, stream, header): pass

  @property
  def _header_declarations(self):
    if self.__hdecls is None:
      self.__hdecls = _Builder()
      self.render_declarations(self.__hdecls, True)
    return self.__hdecls

  @property
  def _header_definitions(self):
    if self.__hdefs is None:
      self.__hdefs = _Builder()
      self.render_definitions(self.__hdefs, True)
    return self.__hdefs
      
  @property
  def _source_declarations(self):
    if self.__sdecls is None:
      self.__sdecls = _Builder()
      self.render_declarations(self.__sdecls, False)
    return self.__sdecls

  @property
  def _source_definitions(self):
    if self.__sdefs is None:
      self.__sdefs = _Builder()
      self.render_definitions(self.__sdefs, False)
    return self.__sdefs


class _DependencySet(set):
  def __init__(self, entity, *args, **kwargs):
    super().__init__(*args, **kwargs)
    self.entity = entity

  def add(self, entity):
    self.entity.references.add(entity)
    super().add(entity)
    
  def update(self, *entities):
    self.entity.references.update(*entities)
    super().update(*entities)

