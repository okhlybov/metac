_caption = f"/* Automagically generated by metac {metac.__version__} */"


class _EntityContainer:
  def __init__(self, *args, **kwargs):
    super().__init__(*args, **kwargs)
    self.entities = set()

  def add(self, entity):
    self.entities.add(entity)
    return self


class _Builder(list):
  def __init__(self, *args, **kwargs):
    super().__init__(*args, **kwargs)
    self.complexity = 0

  def append(self, obj):
    s = str(obj)
    self.complexity += len(s)
    super().append(s)


class _SmartRenderer:
  def __init__(self, *args, **kwargs):
    super().__init__(*args, **kwargs)

  @property
  def digest(self):
    return self.__digest
  
  def render(self):
    stream = self.stream
    path = stream.path
    target = os.path.join(self.module.directory, self.file_name)
    try:
      self.render_contents(stream)
      self.__digest = stream.digest
    finally:
      stream.close()
    if not os.path.exists(target):
      os.replace(path, target)
    elif self.module.stateful:
      if self.module.digests.get(self.file_name) != self.__digest:
        os.replace(path, target)
      else:
        os.unlink(path)
    else:
      if not filecmp.cmp(path, target, shallow=False):
        os.replace(path, target)
      else:
        os.unlink(path)


def _sort_entities(entities):
  return sorted(entities, key=lambda e: e._order_key)


