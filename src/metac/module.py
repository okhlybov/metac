class SystemHeader(Code):
  def __init__(self, header, *args, **kwargs):
    self.header_name = header
    super().__init__(interface=f"#include <{header}>\n", *args, **kwargs)

  def __repr__(self):
    return f"{self.header_name} <{self.__class__.__name__}>"


class _ModuleProxy(types.ModuleType):
  # Calling the module directly constructs the rendering context so the
  # module scripts read `with metac.module(name) as m:` - equivalent to
  # `with metac.module.Module(name) as m:` while every attribute of the
  # module (Module, Code, Header, ...) stays directly accessible
  def __call__(self, *args, **kwargs):
    return Module(*args, **kwargs)


sys.modules[__name__].__class__ = _ModuleProxy